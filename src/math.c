double atan2(double y, double x)
{
        if (x > 0)
                return atan(y / x);
        if (x < 0 && y >= 0)
                return atan(y / x) + PI;
        if (x < 0 && y < 0)
                return atan(y / x) - PI;
        if (x == 0 && y > 0)
                return PI / 2;
        if (x == 0 && y < 0)
                return -PI / 2;
        return 0;
}
